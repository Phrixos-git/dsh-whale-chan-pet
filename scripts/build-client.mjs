// Build lib/client.js in the DSH client-module format.
//
// The browser half is a single `window.__ModuleLoader__.load({ id, factory })`
// bundle. The factory has no static import support, so the source modules are
// concatenated in dependency order after their import/export syntax is removed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const entryId = 'dsh-whale-chan-pet';

const modules = [
  'src/client/sprites.js',
  'src/client/speech.js',
  'src/client/activity.js',
  'src/client/controller.js',
  'src/client/pet.js',
];

const css = readFileSync(new URL('src/client/styles.css', root), 'utf8');

function stripModuleSyntax(source, file) {
  let output = source
    .replace(/^\s*import\s+[^\n]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^\s*export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+(?=(?:const|let|var|function|class|async)\b)/gm, '');

  if (/^\s*import\s/m.test(output)) {
    throw new Error(`${file}: an import survived stripping; update scripts/build-client.mjs`);
  }
  if (/^\s*export\s*\{/m.test(output)) {
    throw new Error(`${file}: an export list survived stripping; update scripts/build-client.mjs`);
  }
  return output;
}

const parts = modules.map((rel) => {
  const source = readFileSync(new URL(rel, root), 'utf8');
  return `// ===================== ${rel} =====================\n${stripModuleSyntax(source, rel)}`;
});

const bundle = `// Generated by scripts/build-client.mjs. Do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(entryId)},
  factory: (require) => {
    const module = { exports: {} };
    const exports = module.exports;
    const React = require("react");
    const ART_CSS = ${JSON.stringify(css)};

${parts.join('\n\n')}
    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  },
});
`;

const target = fileURLToPath(new URL('lib/client.js', root));
writeFileSync(target, bundle);
console.log(`built lib/client.js (${bundle.length} bytes, ${modules.length} modules)`);
